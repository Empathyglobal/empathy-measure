import React from "react";
import { assessmentEnabled } from "@/lib/release-config";
import { Link } from "react-router-dom";
import {
  AGE_BANDS,
  EXACT_AGES,
  SAMPLE_RADAR,
  themesForBand,
  isMinorBand,
  bandFor,
  contextQuestionsFor,
} from "@/components/cookie/cookie";
import SkillRadar from "@/components/empathy/SkillRadar";
import LanguageSelect from "@/components/empathy/LanguageSelect";
import ContextQuestions from "@/components/empathy/ContextQuestions";
import Footer from "@/components/empathy/Footer";


const NOT_A_DIAGNOSIS =
  "This is a picture of skills at one moment. It is not a diagnosis, not a personality type, and not a prediction about anyone.";
const STORAGE_LINE =
  "Use nicknames, not identifying names. If enabled by this installation’s operator, answers and context are sent to its Base44 and AI providers. This community edition does not create assessment records or send result emails. Full results and unfinished answers are saved in this browser. Provider retention policies still apply. Do not use a shared device for private answers.";
const CONSENT_LABEL =
  "I am the parent or guardian of this child and I agree to these answers being used to write the result.";
const SUBHEADING =
  "An experimental conversation about seven empathy-related skills. Scores are generated by a model and have not been independently validated.";
const ABOUT_TIME =
  "About ten minutes. Ages 7 and up answer for themselves. For a child under 7, a parent answers about them.";
const NICKNAME_LINE =
  "Choose a nickname. Your result appears on screen. This community edition does not send result emails.";

function exactAgeLabel(age) {
  return age === 0 ? "Under 1" : String(age);
}

const inputCls =
  "mt-2 w-full rounded-xl border border-input bg-secondary px-4 py-3 text-[15px] text-foreground outline-none focus:border-primary";

export default function LandingView({
  band,
  onBandChange,
  exactAge,
  setExactAge,
  theme,
  onThemeChange,
  context,
  setContext,
  language,
  setLanguage,
  name,
  setName,
  childName,
  setChildName,
  consent,
  setConsent,
  onBegin,
  loading,
}) {
  const bandObj = band ? bandFor(band) : null;
  const mode = bandObj ? bandObj.mode : null;
  const isExactBand = !!(bandObj && bandObj.exact);
  const parentReport = mode === "parent_report";
  const parentFronted = parentReport || (band && isMinorBand(band));
  const showTheme = !!band && !isExactBand;
  const themeOptions = showTheme ? themesForBand(band) : [];

  const ctxKey = band && bandFor(band).exact ? "under7" : theme;
  const contextReady = (() => {
    if (!ctxKey) return true;
    const qs = contextQuestionsFor(ctxKey);
    return qs.every(
      (q) =>
        !q.required ||
        (context[q.key] != null && String(context[q.key]).trim() !== "")
    );
  })();

  const ready =
    !!band &&
    (!isExactBand || exactAge != null) &&
    (!showTheme || !!theme) &&
    contextReady &&
    name.trim().length > 0 &&
    (!parentFronted || (childName.trim().length > 0 && consent));

  return (
    <div className="mx-auto max-w-3xl px-5 pb-20 pt-10">
      {!assessmentEnabled && <p role="status" className="rounded-xl border border-border p-4 text-sm">Community source preview: live assessment is disabled. You can explore the sample results. An operator must configure a separate backend and review privacy and security before enabling assessment.</p>}
      <div className="hero-wash -mx-5 px-5 pb-12 pt-12">
        <header className="text-center">
          <p className="text-xs font-medium uppercase tracking-[0.2em] text-primary">
            The Empathy Measure
          </p>
          <h1 className="mt-4 font-heading text-4xl font-semibold leading-[1.05] tracking-tight text-foreground sm:text-5xl">
            The Empathy Measure
          </h1>
          <p className="mx-auto mt-5 max-w-xl text-base text-muted-foreground">
            {SUBHEADING}
          </p>
        </header>
        <p className="body-text mt-8 text-center font-medium">{NOT_A_DIAGNOSIS}</p>
      </div>

      <div className="mt-10 grid gap-4 sm:grid-cols-3">
        <MarketingBlock
          title="It adapts to you."
          body="Answer well and the next question gets harder. Answer thinly and it comes back simpler. Your score reflects how far up you got, not just how nicely you wrote."
        />
        <MarketingBlock
          title="No boxes to tick."
          body="Every answer is written in your own words and read in full. Open answers provide material for reflection, but can be influenced by wording, language, and deliberate manipulation."
        />
        <MarketingBlock
          title="It measures what matters."
          body="Not personality. Seven skills that decide how a disagreement ends, whether people feel heard, and how fast you recover from being treated badly."
        />
      </div>

      <section className="lift-card mt-10 rounded-2xl border border-border bg-card p-5 sm:p-6">
        <p className="text-sm font-medium text-foreground">
          Choose your age group. The questions are written for your reading age.
        </p>
        <div className="mt-4 grid grid-cols-2 gap-3 sm:grid-cols-3">
          {AGE_BANDS.map((b) => {
            const active = band === b.key;
            return (
              <button
                key={b.key}
                type="button"
                onClick={() => onBandChange(b.key)}
                className={
                  "rounded-xl border px-3 py-3 text-sm font-medium transition " +
                  (active
                    ? "border-primary bg-primary text-primary-foreground"
                    : "border-border bg-secondary text-foreground hover:border-accent")
                }
              >
                {b.label}
              </button>
            );
          })}
        </div>

        {isExactBand && (
          <div className="mt-6">
            <p className="text-sm font-medium text-foreground">How old exactly?</p>
            <div className="mt-3 grid grid-cols-4 gap-2 sm:grid-cols-7">
              {EXACT_AGES.map((age) => {
                const active = exactAge === age;
                return (
                  <button
                    key={age}
                    type="button"
                    onClick={() => setExactAge(age)}
                    className={
                      "rounded-xl border px-2 py-3 text-sm font-medium transition " +
                      (active
                        ? "border-primary bg-primary text-primary-foreground"
                        : "border-border bg-secondary text-foreground hover:border-accent")
                    }
                  >
                    {exactAgeLabel(age)}
                  </button>
                );
              })}
            </div>
          </div>
        )}

        {showTheme && (
          <div className="mt-6">
            <p className="text-sm font-medium text-foreground">
              Choose the part of life you want the questions to be about.
            </p>
            {themeOptions.length === 0 ? (
              <p className="mt-3 text-sm text-muted-foreground">
                Pick an age group to see the themes.
              </p>
            ) : (
              <div className="mt-3 space-y-2">
                {themeOptions.map((t) => {
                  const active = theme === t.key;
                  return (
                    <button
                      key={t.key}
                      type="button"
                      onClick={() => onThemeChange(t.key)}
                      className={
                        "block w-full rounded-xl border px-4 py-3 text-left transition " +
                        (active
                          ? "border-primary bg-accent"
                          : "border-border bg-secondary hover:border-accent")
                      }
                    >
                      <span className="text-sm font-semibold text-foreground">{t.label}</span>
                      <span className="block text-sm text-muted-foreground">{t.blurb}</span>
                    </button>
                  );
                })}
              </div>
            )}
          </div>
        )}

        {showTheme && theme && (
          <ContextQuestions theme={theme} context={context} setContext={setContext} />
        )}

        <div className="mt-6">
          <LanguageSelect value={language} onChange={setLanguage} />

          {parentFronted ? (
            <>
              <p className="mt-6 text-sm font-medium text-foreground">
                {parentReport
                  ? "You are answering for your child. Tell us who you are."
                  : "A parent or guardian needs to agree first. Tell us who you are."}
              </p>
              <div className="mt-3 grid gap-3 sm:grid-cols-2">
                <label className="block">
                  <span className="text-sm font-medium text-foreground">Your nickname</span>
                  <input
                    type="text"
                    value={name}
                    onChange={(e) => setName(e.target.value)}
                    placeholder="Your nickname"
                    className={inputCls}
                  />
                </label>
              </div>
              <label className="mt-3 block">
                <span className="text-sm font-medium text-foreground">Your child's nickname</span>
                <input
                  type="text"
                  value={childName}
                  onChange={(e) => setChildName(e.target.value)}
                  placeholder="Your child's nickname"
                  className={inputCls}
                />
              </label>
              {isExactBand && (
                <ContextQuestions theme="under7" context={context} setContext={setContext} />
              )}
            </>
          ) : (
            <>
              <p className="mt-6 text-sm font-medium text-foreground">{NICKNAME_LINE}</p>
              <div className="mt-3 grid gap-3 sm:grid-cols-2">
                <label className="block">
                  <span className="text-sm font-medium text-foreground">Your nickname</span>
                  <input
                    type="text"
                    value={name}
                    onChange={(e) => setName(e.target.value)}
                    placeholder="Your nickname"
                    className={inputCls}
                  />
                </label>
              </div>
            </>
          )}

          <p className="mt-4 text-xs text-muted-foreground">{STORAGE_LINE}</p>

          {parentFronted && (
            <label className="mt-4 flex items-start gap-3">
              <input
                type="checkbox"
                checked={consent}
                onChange={(e) => setConsent(e.target.checked)}
                className="mt-1 h-4 w-4 rounded border-border accent-primary"
              />
              <span className="text-sm text-foreground">{CONSENT_LABEL}</span>
            </label>
          )}


        </div>

        <button
          type="button"
          disabled={!assessmentEnabled || !ready || loading}
          onClick={onBegin}
          className="btn-lift btn-primary-lift mt-6 w-full rounded-xl bg-primary px-6 py-4 text-base font-semibold text-primary-foreground transition enabled:hover:bg-primary/90 disabled:cursor-not-allowed disabled:opacity-40"
        >
          {loading ? "Starting..." : "Begin"}
        </button>

        <p className="mt-3 text-center text-xs text-muted-foreground">{ABOUT_TIME}</p>

        <div className="mt-6 rounded-2xl border border-border bg-secondary p-5">
          <p className="text-sm font-semibold text-foreground">What you get at the end</p>
          <p className="mt-2 text-sm text-muted-foreground">Seven skills, and for each one the moment in your own answers that showed it, what it means, and one small thing to practise. A real line from a finished result reads: each night, name one feeling from the day in a word more exact than annoyed or fine.</p>
          {parentReport && (
            <p className="mt-2 text-sm text-muted-foreground">You also get a version written for your child to read, so you have the words for the conversation.</p>
          )}
        </div>
      </section>

      <section className="lift-card mt-10 rounded-2xl border border-border bg-card p-5">
        <SkillRadar data={SAMPLE_RADAR} />
        <p className="mt-2 text-center text-xs uppercase tracking-widest text-muted-foreground">
          Sample result
        </p>
        <div className="mt-4 flex flex-wrap justify-center gap-3">
          <Link
            to="/samples"
            className="btn-lift btn-primary-lift rounded-xl bg-primary px-6 py-3 text-base font-semibold text-primary-foreground transition hover:bg-primary/90"
          >
            See sample results
          </Link>
          <Link
            to="/how-it-works"
            className="btn-lift rounded-xl border border-border bg-card px-6 py-3 text-base font-semibold text-foreground transition hover:bg-secondary"
          >
            How it works
          </Link>
          <Link
            to="/research"
            className="btn-lift rounded-xl border border-border bg-card px-6 py-3 text-base font-semibold text-foreground transition hover:bg-secondary"
          >
            The research
          </Link>
        </div>
      </section>

      <Footer />
    </div>
  );
}

function MarketingBlock({ title, body }) {
  return (
    <div className="lift-card lift-hover rounded-2xl border border-border bg-card p-5">
      <p className="text-base font-semibold text-foreground">{title}</p>
      <p className="mt-2 text-sm text-muted-foreground">{body}</p>
    </div>
  );
}